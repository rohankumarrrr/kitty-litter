import XCTest

final class TextFitTests: XCTestCase {
    func testAddsASpaceAfterAWord() {
        XCTAssertEqual(TextFit.fit("Thanks.", before: "All done.", after: nil), " Thanks.")
    }

    func testNoSpaceAfterSpaceOrAtStart() {
        XCTAssertEqual(TextFit.fit("Thanks.", before: "All done. ", after: nil), "Thanks.")
        XCTAssertEqual(TextFit.fit("Thanks.", before: "", after: nil), "Thanks.")
        XCTAssertEqual(TextFit.fit("Thanks.", before: nil, after: nil), "Thanks.")
    }

    func testLowercasesMidSentence() {
        XCTAssertEqual(TextFit.fit("The build is green.", before: "I think that", after: nil), " the build is green.")
    }

    func testKeepsCapitalsThatMatter() {
        XCTAssertEqual(TextFit.fit("I agree.", before: "and then", after: nil), " I agree.")
        XCTAssertEqual(TextFit.fit("GitHub is down.", before: "I think", after: nil), " GitHub is down.")
        XCTAssertEqual(TextFit.fit("Mike agrees.", before: "I think", after: nil), " Mike agrees.")
    }

    func testCapitalStaysAfterASentenceOrNewLine() {
        XCTAssertEqual(TextFit.fit("The build is green.", before: "Done. ", after: nil), "The build is green.")
        XCTAssertEqual(TextFit.fit("The build is green.", before: "Done\n", after: nil), "The build is green.")
    }

    func testMiddleOfALineDropsTheStopAndAddsASpace() {
        XCTAssertEqual(TextFit.fit("the blue one.", before: "I want ", after: "for now"), "the blue one ")
        XCTAssertEqual(TextFit.fit("the blue one.", before: "I want ", after: " for now"), "the blue one")
    }

    func testBeforePunctuationKeepsTogether() {
        XCTAssertEqual(TextFit.fit("the blue one", before: "I want ", after: ", please"), "the blue one")
        XCTAssertEqual(TextFit.fit("the blue one.", before: "I want ", after: "."), "the blue one")
    }

    func testARewriteKeepsTheSelectionsSpacingAtEachEnd() {
        XCTAssertEqual(TextFit.inPlace(of: "We wanted to say hi.\n", "Hi."), "Hi.\n")
        XCTAssertEqual(TextFit.inPlace(of: " two words ", "\nfew words\n"), " few words ")
        XCTAssertEqual(TextFit.inPlace(of: "plain", "Plain"), "Plain")
    }
}

final class PasteboardSnapshotTests: XCTestCase {
    private var pasteboard: NSPasteboard!

    override func setUp() {
        // A private pasteboard, so these tests never touch the real clipboard.
        pasteboard = NSPasteboard(name: NSPasteboard.Name("shades.voice.tests.\(UUID().uuidString)"))
    }

    override func tearDown() {
        pasteboard.releaseGlobally()
    }

    func testDictatedTextIsMarkedTransient() {
        PasteboardSnapshot.write("hello", to: pasteboard)
        let item = pasteboard.pasteboardItems?.first
        XCTAssertEqual(item?.string(forType: .string), "hello")
        XCTAssertNotNil(item?.data(forType: PasteboardSnapshot.transient))
        XCTAssertNotNil(item?.data(forType: PasteboardSnapshot.autoGenerated))
    }

    func testRestoresEveryTypeOfEveryItem() {
        let first = NSPasteboardItem()
        first.setString("plain", forType: .string)
        first.setData(Data("<b>rich</b>".utf8), forType: .html)
        let second = NSPasteboardItem()
        second.setData(Data([1, 2, 3]), forType: NSPasteboard.PasteboardType("com.example.custom"))
        pasteboard.clearContents()
        pasteboard.writeObjects([first, second])

        let saved = PasteboardSnapshot(pasteboard)
        PasteboardSnapshot.write("dictated", to: pasteboard)
        saved.restore(to: pasteboard)

        let items = pasteboard.pasteboardItems ?? []
        XCTAssertEqual(items.count, 2)
        XCTAssertEqual(items.first?.string(forType: .string), "plain")
        XCTAssertEqual(items.first?.data(forType: .html), Data("<b>rich</b>".utf8))
        XCTAssertEqual(items.last?.data(forType: NSPasteboard.PasteboardType("com.example.custom")), Data([1, 2, 3]))
        XCTAssertFalse(pasteboard.string(forType: .string) == "dictated")
    }

    func testRestoringAnEmptyClipboardLeavesItEmpty() {
        pasteboard.clearContents()
        let saved = PasteboardSnapshot(pasteboard)
        PasteboardSnapshot.write("dictated", to: pasteboard)
        saved.restore(to: pasteboard)
        XCTAssertNil(pasteboard.string(forType: .string))
    }

    func testPasteOnlyApps() {
        XCTAssertTrue(TextInserter.isPasteOnly("com.google.Chrome"))
        XCTAssertTrue(TextInserter.isPasteOnly("com.microsoft.VSCode"))
        XCTAssertTrue(TextInserter.isPasteOnly("com.apple.Terminal"))
        XCTAssertTrue(TextInserter.isPasteOnly(nil))
        XCTAssertFalse(TextInserter.isPasteOnly("com.apple.TextEdit"))
        XCTAssertFalse(TextInserter.isPasteOnly("com.apple.Notes"))
    }
}
